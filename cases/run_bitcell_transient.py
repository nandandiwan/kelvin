"""Transient thermal response of the real bitcell to a compact-model-driven
workload turning on, then off: sustained duty-cycle-averaged active power
(same magnitude as cases/run_bitcell_compact.py's steady case) until Tmax
approaches steady state, then zero-source idle until it relaxes back near
ambient. Saves every step's full temperature field (not just Tmax) so
figures/animations can be re-rendered later without re-solving -- see
cases/render_transient_layers.py, which does exactly that for a
fixed-viewpoint isometric layer-stack GIF of the hot spot forming.
Every X0..X7 channel receives its own instance's compact-model power through
gds.bitcell_mapping, including asymmetric HOLD/READ/WRITE operating points.

The default power model is a validated transient-SPICE READ-1. In sustained
mode, each device and local layout resistor receives its integrated event heat
times the access rate. --interconnect none selects the former ideal-wire model.
`--instantaneous` follows the complete per-source electrical waveforms, using
their exact piecewise-linear energy integral over each thermal timestep.
The electrical and thermal timesteps are independent. Power is never scaled
from an instantaneous sample or shared by transistor class. DC/timing models
remain available explicitly with --power-model dc-surrogate.

This is one-way electrical-to-thermal coupling, not temperature feedback or
an extracted full-macro workload. See SPICE_TRANSIENT.md for assumptions.

The notebook polygon mesh is the default. --mesh-manifest reuses the exact
mesh generated by read_gds.ipynb; --mesh-method legacy --interconnect none
selects the old boxes.

Lateral boundaries are periodic in x/y by default, as in the compact steady
case. --lateral-bc insulating restores zero-flux sidewalls. Periodicity
repeats the same geometry and workload by translation, not reflection.

    python cases/run_bitcell_transient.py [--point read_1] [--row-hit-rate 1.0]
    python cases/run_bitcell_transient.py --point read_1 --instantaneous
"""

